"""Regenerate examples/img/*.png and examples/README.md from c4shap.positions.

    python examples/make_examples.py

Needs only numpy + matplotlib (no shap / torch). Uses the exact solver for the 'solver says'
column, so the hard positions take a second or two each.
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from c4shap.board import Board  # noqa: E402
from c4shap.groups import cell_name, explain_groups  # noqa: E402
from c4shap.positions import POSITIONS  # noqa: E402
from c4shap.solver import Position, Solver, score_to_text  # noqa: E402
from c4shap.viz import plot_groups  # noqa: E402

here = Path(__file__).parent
(here / "img").mkdir(exist_ok=True)
solver = Solver()

md = ["# Examples", "",
      "Generated by `make_examples.py`. Gold = side to move, grey = opponent. Green bars are the mover's",
      "groups, red bars the opponent's (thicker = more valuable); dashed rings mark each group's empty",
      "completion cells; the green ring is the recommended landing cell.", ""]
for kind, heading in (("tactic", "Tactics the group explainer is built for"),
                      ("hard", "Positions where the solver sees more")):
    md += [f"## {heading}", ""]
    for p in [p for p in POSITIONS if p.kind == kind]:
        board = Board.from_moves(p.moves)
        exp = explain_groups(board)
        pos = Position.from_moves(p.moves)
        scores = solver.move_scores(pos)
        best = max(s for s in scores if s is not None)
        solver_cols = [c + 1 for c, s in enumerate(scores) if s == best]
        pick = exp.best
        fig = plot_groups(exp, str(here / "img" / f"{p.name}.png"), title=p.title)
        plt.close(fig)
        agree = "agrees" if pick.col + 1 in solver_cols else "**disagrees**"
        md += [f"### {p.title}", "", f"`c4shap {p.moves} --explainer groups` &nbsp; (position `{p.name}`)", "",
               f"![{p.name}](img/{p.name}.png)", "", p.note, "",
               f"- group explainer: column {pick.col + 1} ({cell_name(pick.cell)}), score {pick.score:+.1f}",
               f"- exact solver: column(s) {', '.join(map(str, solver_cols))} - {score_to_text(best, pos.moves)}",
               f"- the explainer {agree} with the solver", ""]
(here / "README.md").write_text("\n".join(md))
print("wrote", len(POSITIONS), "examples")
